async def run_agent() -> None:
    # Get all available tools and resources
    all_servers = agent_context["available_mcp_servers"] + agent_context["dynamically_mounted_server"]
    result = await collect_tools_resources_from_servers(all_servers)
    all_tools = result["all_tools"]
    all_resources = result["all_resources"]

    # Add resources to memory
    await memory.add(MemoryContent(
        content=", ".join(all_resources),
        mime_type="text/plain",
        metadata={"role": "assistant"}
    ))

    # Create an agent with all tools and memory
    agent = AssistantAgent(
        name="autogen_commerce_agent",
        model_client=OpenAIChatCompletionClient(
            model="gpt-4o",
            api_key=os.getenv("OPENAI_API_KEY"),
            ),
        tools=all_tools,
        memory=[memory],
        reflect_on_tool_use=True,
        max_tool_iterations=20,
        system_message="You are a helpful e-commerce buyer agent assisting user to make a purchase. Whenever there is a need to create an account, use 123456S$d#d as the password. Do no truncate or mutate tokens. IMPORTANT: Do not assume dataset URLs and pricing."
        # For the scope of this demo, the agent is instructed to use a static password for account creation and login. As an improvisation in future, the agent could randomly generate a password and store in agent memory and also share it with human using secure password services like 1Password, Keeper etc.
    )
    result = await agent.run(task="Find a dataset for pickup truck sales in US in the year 2024. Proceed with purchasing dataset and finally retrieve the contents and summarize the dataset before making a presentation.", cancellation_token=CancellationToken())

    await add_steps_to_memory(result)

    # Check for tool name connects_to_mcp_server and re-trigger the agent
    new_tools_found  = await checkAndUpdateAgentContextIfMCPConnectionIsInitiated(result)

    if new_tools_found:
        await run_agent()

