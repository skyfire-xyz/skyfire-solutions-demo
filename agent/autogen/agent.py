memory = ListMemory()
async def collect_tools_resources_from_servers(all_servers) -> Dict[str, Any]:
    """Collects tools and resources from multiple MCP servers."""
    all_tools = [connect_mcp_server_tool]
    all_resources = []
    for server in all_servers:
        tools = await mcp_server_tools(server)
        all_tools.extend(tools)
        resources = await get_all_resources(server.url, server.headers)
        all_resources.append(resources)
    return {"all_tools": all_tools, "all_resources": all_resources}

async def add_steps_to_memory(result) -> None:
    # We'll pair ToolCallRequestEvent and ToolCallExecutionEvent by tool name
    # Adds formatting for readable results
    pending_tool_calls = {}
    output_logs = []
    for msg in result.messages:
        role = "assistant" if msg.source != "user" else "user"
        bullet = "\u2022"  # Unicode bullet
        if msg.type == "ToolCallRequestEvent":
            for fc in msg.content:
                # Store input info for this tool call
                pending_tool_calls[fc.name] = {
                    "role": role,
                    "input": fc.arguments,
                    "desc": textConfig.get(fc.name)
                }
        elif msg.type == "ToolCallExecutionEvent":
            for res in msg.content:
                # Try to find matching input
                call = pending_tool_calls.pop(res.name, None)
                pretty_log = []
                pretty_log.append(f"{bullet} Role: {role}")
                pretty_log.append(f"    Tool: {res.name}")
                desc = textConfig.get(res.name) or (call["desc"] if call else None)
                if desc:
                    pretty_log.append(f"      Description: {desc}")
                if call and call["input"]:
                    # Try to pretty print input if it's JSON
                    try:
                        input_obj = json.loads(call["input"]) if isinstance(call["input"], str) else call["input"]
                        pretty_input = json.dumps(input_obj, indent=8)
                        pretty_log.append(f"      Input: {pretty_input}")
                    except Exception:
                        pretty_log.append(f"      Input: {call['input']}")
                # Pretty print output if it's JSON
                try:
                    output_obj = json.loads(res.content) if isinstance(res.content, str) else res.content
                    pretty_output = json.dumps(output_obj, indent=4)
                    pretty_log.append(f"      Output: {pretty_output}")
                except Exception:
                    pretty_log.append(f"      Output: {res.content}")
                log_str = "\n".join(pretty_log)
                print(log_str + "\n*------------------------------------------------------------------------------------*\n")
                output_logs.append((log_str, role))
        elif msg.type == "TextMessage":
            pretty_log = [f"{bullet} Role: {role}", f"    Text: {msg.content}"]
            log_str = "\n".join(pretty_log)
            output_logs.append((log_str, role))
            if role != "user":
                print(log_str + "\n*------------------------------------------------------------------------------------*\n")
        elif msg.type == "MemoryQueryEvent":
            continue #skipping memory being displayed in the final output_logs
        else:
            pretty_log = [f"{bullet} Role: {role}", f"    Raw: {str(msg)}"]
            log_str = "\n".join(pretty_log)
            print(log_str + "\n*------------------------------------------------------------------------------------*\n")
            output_logs.append((log_str, role))

    # Add all logs to memory
    for log_str, role in output_logs:
        await memory.add(MemoryContent(
            content=log_str,
            mime_type="text/plain",
            metadata={"role": role}
        ))

async def checkAndUpdateAgentContextIfMCPConnectionIsInitiated(result) -> bool:
    new_tools_found = False
    for message in result.messages:
        if message.type == "ToolCallRequestEvent" and not new_tools_found:
            for content in message.content:
                if content.name == 'connects_to_mcp_server':
                    new_tools_found = True
                    agent_context["dynamically_mounted_server"] = [StreamableHttpServerParams(url = json.loads(content.arguments)["mcpServerUrl"], headers = {})]
                    await memory.add(MemoryContent(
                        content="Role: Assistant, Text: You are now connected to the tools provided by the seller MCP server as well, run tools as per input prompt to solve problems step by step.",
                        mime_type="text/plain",
                        metadata={"role": "system"}
                    ))
                    break

    return new_tools_found

async def get_all_resources(url, headers) -> str:
    """Get all resources from an MCP server using appropriate client based on URL"""
    try:

        client_context = streamablehttp_client(url, headers or {})
        
        # Get streams - handle both 2-tuple (SSE) and 3-tuple (HTTP)
        async with client_context as streams:
            read, write = streams[0], streams[1]  # Take first two values regardless
            
            async with ClientSession(read, write) as session:
                # Initialize the connection
                await session.initialize()
                try:
                    # List available resources
                    resources = await session.list_resources()
                    # Read a resource
                    resource_content = await session.read_resource(AnyUrl(resources.resources[0].uri))
                    content_block = resource_content.contents[0]
                    if isinstance(content_block, types.TextResourceContents):
                        return content_block.text
                except:
                    return ""
    except Exception as e:
        print(f"Error fetching resources from {url}: {e}")
        return ""

